/**
 * Normalizes a city or township name for unique duplicate comparison.
 */
export function normalizeLocationKey(value) {
  return String(value || '')
    .trim()
    .replace(/\s+/g, ' ')
    .toLowerCase();
}

/**
 * Deep-clones and deduplicates a catalog array of `{ city: string, townships: string[] }`.
 */
export function sanitizeLocationCatalog(catalog) {
  const list = Array.isArray(catalog) ? catalog : [];
  const cityMap = new Map();

  for (const entry of list) {
    const cityName = String(entry?.city || '').trim().replace(/\s+/g, ' ');
    if (!cityName) continue;
    const cityKey = normalizeLocationKey(cityName);

    if (!cityMap.has(cityKey)) {
      cityMap.set(cityKey, {
        city: cityName,
        townshipMap: new Map(),
      });
    }

    const bucket = cityMap.get(cityKey);
    const tsps = Array.isArray(entry?.townships) ? entry.townships : [];
    for (const t of tsps) {
      const tName = String(t || '').trim().replace(/\s+/g, ' ');
      if (!tName) continue;
      const tKey = normalizeLocationKey(tName);
      if (!bucket.townshipMap.has(tKey)) {
        bucket.townshipMap.set(tKey, tName);
      }
    }
  }

  return Array.from(cityMap.values()).map((b) => ({
    city: b.city,
    townships: Array.from(b.townshipMap.values()),
  }));
}

/**
 * Builds the active unified catalog from:
 * 1) Firestore `settings/myanmar_locations` (`storedCatalog`, or falls back to `DEFAULT_MYANMAR_LOCATIONS` if not seeded yet)
 * 2) Optionally merges any approved legacy documents from `locations` collection.
 */
export function buildUnifiedLocationCatalog(storedCatalog = null, approvedLegacyDocs = []) {
  const baseCatalog =
    Array.isArray(storedCatalog) && storedCatalog.length > 0
      ? sanitizeLocationCatalog(storedCatalog)
      : sanitizeLocationCatalog(DEFAULT_MYANMAR_LOCATIONS);

  const cityMap = new Map();
  for (const item of baseCatalog) {
    cityMap.set(normalizeLocationKey(item.city), {
      city: item.city,
      townships: [...item.townships],
      townshipKeys: new Set(item.townships.map(normalizeLocationKey)),
    });
  }

  // Merge any approved legacy location docs uniquely
  for (const docItem of Array.isArray(approvedLegacyDocs) ? approvedLegacyDocs : []) {
    if (docItem?.status === 'pending') continue;
    const cityName = String(docItem?.city || '').trim().replace(/\s+/g, ' ');
    const tspName = String(docItem?.township || '').trim().replace(/\s+/g, ' ');
    if (!cityName) continue;

    const cityKey = normalizeLocationKey(cityName);
    if (!cityMap.has(cityKey)) {
      cityMap.set(cityKey, {
        city: cityName,
        townships: [],
        townshipKeys: new Set(),
      });
    }
    const bucket = cityMap.get(cityKey);
    if (tspName) {
      const tKey = normalizeLocationKey(tspName);
      if (!bucket.townshipKeys.has(tKey)) {
        bucket.townshipKeys.add(tKey);
        bucket.townships.push(tspName);
      }
    }
  }

  return Array.from(cityMap.values()).map((b) => ({
    city: b.city,
    townships: b.townships,
  }));
}

/**
 * Merges `DEFAULT_MYANMAR_LOCATIONS` into an existing catalog without losing any custom cities/townships.
 */
export function mergeDefaultMyanmarLocations(currentCatalog = []) {
  const base = sanitizeLocationCatalog(DEFAULT_MYANMAR_LOCATIONS);
  const current = sanitizeLocationCatalog(currentCatalog);
  const merged = [...base];
  const cityIndexByKey = new Map(merged.map((c, idx) => [normalizeLocationKey(c.city), idx]));

  for (const item of current) {
    const cKey = normalizeLocationKey(item.city);
    if (cityIndexByKey.has(cKey)) {
      const target = merged[cityIndexByKey.get(cKey)];
      const existingKeys = new Set(target.townships.map(normalizeLocationKey));
      for (const tsp of item.townships) {
        if (!existingKeys.has(normalizeLocationKey(tsp))) {
          existingKeys.add(normalizeLocationKey(tsp));
          target.townships.push(tsp);
        }
      }
    } else {
      cityIndexByKey.set(cKey, merged.length);
      merged.push({ city: item.city, townships: [...item.townships] });
    }
  }

  return merged;
}

/**
 * Adds a unique City + Township pair into the catalog.
 * Returns `{ catalog, added, reason }`.
 */
export function addUniqueLocationToCatalog(catalog, rawCity, rawTownship) {
  const city = String(rawCity || '').trim().replace(/\s+/g, ' ');
  const township = String(rawTownship || '').trim().replace(/\s+/g, ' ');
  if (!city) {
    return { catalog: sanitizeLocationCatalog(catalog), added: false, reason: 'missing_city' };
  }

  const next = sanitizeLocationCatalog(catalog);
  const cKey = normalizeLocationKey(city);
  let cityEntry = next.find((item) => normalizeLocationKey(item.city) === cKey);

  if (!cityEntry) {
    cityEntry = { city, townships: township ? [township] : [] };
    next.push(cityEntry);
    return { catalog: next, added: true, reason: 'city_and_township_added' };
  }

  if (!township) {
    return { catalog: next, added: false, reason: 'duplicate_city' };
  }

  const tKey = normalizeLocationKey(township);
  const existsTsp = cityEntry.townships.some((t) => normalizeLocationKey(t) === tKey);
  if (existsTsp) {
    return { catalog: next, added: false, reason: 'duplicate_township' };
  }

  cityEntry.townships.push(township);
  return { catalog: next, added: true, reason: 'township_added' };
}

/**
 * Removes a township from a city in the catalog.
 */
export function removeTownshipFromCatalog(catalog, city, township) {
  const cKey = normalizeLocationKey(city);
  const tKey = normalizeLocationKey(township);
  return sanitizeLocationCatalog(catalog).map((item) => {
    if (normalizeLocationKey(item.city) !== cKey) return item;
    return {
      ...item,
      townships: item.townships.filter((t) => normalizeLocationKey(t) !== tKey),
    };
  });
}

/**
 * Removes an entire city and its townships from the catalog.
 */
export function removeCityFromCatalog(catalog, city) {
  const cKey = normalizeLocationKey(city);
  return sanitizeLocationCatalog(catalog).filter(
    (item) => normalizeLocationKey(item.city) !== cKey
  );
}

/**
 * Renames a city uniquely in the catalog.
 */
export function renameCityInCatalog(catalog, oldCity, newCity) {
  const cleanNew = String(newCity || '').trim().replace(/\s+/g, ' ');
  if (!cleanNew) return sanitizeLocationCatalog(catalog);
  const oldKey = normalizeLocationKey(oldCity);
  const updated = sanitizeLocationCatalog(catalog).map((item) =>
    normalizeLocationKey(item.city) === oldKey ? { ...item, city: cleanNew } : item
  );
  return sanitizeLocationCatalog(updated);
}

/**
 * Renames a township under a given city uniquely in the catalog.
 */
export function renameTownshipInCatalog(catalog, city, oldTownship, newTownship) {
  const cleanNew = String(newTownship || '').trim().replace(/\s+/g, ' ');
  if (!cleanNew) return sanitizeLocationCatalog(catalog);
  const cKey = normalizeLocationKey(city);
  const oldTKey = normalizeLocationKey(oldTownship);
  const updated = sanitizeLocationCatalog(catalog).map((item) => {
    if (normalizeLocationKey(item.city) !== cKey) return item;
    return {
      ...item,
      townships: item.townships.map((t) =>
        normalizeLocationKey(t) === oldTKey ? cleanNew : t
      ),
    };
  });
  return sanitizeLocationCatalog(updated);
}

/**
 * Gets all unique city names from a catalog.
 */
export function getCitiesFromCatalog(catalog) {
  return sanitizeLocationCatalog(catalog).map((c) => c.city);
}

/**
 * Gets all unique townships for a selected city from a catalog.
 */
export function getTownshipsForCity(catalog, selectedCity) {
  const cKey = normalizeLocationKey(selectedCity);
  if (!cKey) return [];
  const match = sanitizeLocationCatalog(catalog).find(
    (c) => normalizeLocationKey(c.city) === cKey
  );
  return match ? match.townships : [];
}

/**
 * Checks whether a city + township already exists uniquely in the catalog.
 */
export function locationExistsInCatalog(catalog, city, township) {
  const cKey = normalizeLocationKey(city);
  const tKey = normalizeLocationKey(township);
  if (!cKey) return false;
  const match = sanitizeLocationCatalog(catalog).find(
    (c) => normalizeLocationKey(c.city) === cKey
  );
  if (!match) return false;
  if (!tKey) return true;
  return match.townships.some((t) => normalizeLocationKey(t) === tKey);
}

/**
 * Returns total city and township counts in a catalog.
 */
export function countCatalogStats(catalog) {
  const clean = sanitizeLocationCatalog(catalog);
  const cityCount = clean.length;
  const townshipCount = clean.reduce((sum, item) => sum + item.townships.length, 0);
  return { cityCount, townshipCount };
}

/**
 * Paginates an array cleanly for Telegram Bot Inline Keyboard dropdowns.
 */
export function paginateLocationItems(items, page = 0, pageSize = 10) {
  const list = Array.isArray(items) ? items : [];
  const totalPages = Math.max(1, Math.ceil(list.length / pageSize));
  const safePage = Math.max(0, Math.min(Number(page) || 0, totalPages - 1));
  const startIndex = safePage * pageSize;
  const pageItems = list.slice(startIndex, startIndex + pageSize).map((label, offset) => ({
    label,
    index: startIndex + offset,
  }));
  return {
    items: pageItems,
    page: safePage,
    totalPages,
    hasPrev: safePage > 0,
    hasNext: safePage < totalPages - 1,
    totalItems: list.length,
  };
}
